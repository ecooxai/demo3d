import fs from 'node:fs';
import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox','--enable-webgl','--ignore-gpu-blocklist','--use-angle=metal']});
const page = await browser.newPage();
await page.setViewport({width:1000,height:1300});
await page.goto('http://127.0.0.1:4173/?backend=webgl&capture=1',{waitUntil:'networkidle0'});
await page.waitForFunction(()=>document.body.dataset.ready==='true');
await new Promise(r=>setTimeout(r,500));
await page.evaluate(()=>{window.__YUUKAPA__.camera.position.set(0.3,7.0,8.5);window.__YUUKAPA__.controls.target.set(0,6.95,0.3);window.__YUUKAPA__.controls.update();});
await new Promise(r=>setTimeout(r,400));
let data=await page.evaluate(()=>document.querySelector('#scene').toDataURL('image/png'));fs.writeFileSync('output/iteration-001/face-with-patch.png',Buffer.from(data.split(',')[1],'base64'));
await page.evaluate(()=>{window.__YUUKAPA__.character.root.traverse(o=>{if(o.material?.map?.image?.width===1024&&o.material.map.image.height===640)o.visible=false;});});
await new Promise(r=>setTimeout(r,400));
data=await page.evaluate(()=>document.querySelector('#scene').toDataURL('image/png'));fs.writeFileSync('output/iteration-001/face-no-patch.png',Buffer.from(data.split(',')[1],'base64'));
await browser.close();
console.log('done');
